%  (11) Save
%% ---------------------------
stage6C3 = struct();
stage6C3.meta = struct( ...
    'createdOn', char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
    'script', mfilename, 'sourceFile', groupFile, 'binName', binName, ...
    'midWin_percentCV', midWin, ...
    'nBipolar', nB, 'IED_mm', IED_mm, 'climMVA', climMVA, ...
    'sign_note', "centroid differences in the CSV are ECC minus CON", ...
    'note', ["maps are averaged across the analysis window, so no ECC " ...
             "reversal is required"]);

stage6C3.maps     = M;
stage6C3.mapsSub  = mapSub;
stage6C3.centroid = struct('x', CxSub, 'y', CySub, 'table', centroidTable);
stage6C3.coords   = struct('x_ch', x_ch, 'y_ch', y_ch);

save(fullfile(ROOT,'stage6C3_heatmap_mid20to80.mat'), 'stage6C3', '-v7.3');

fprintf('\nSaved results  : %s\n', fullfile(ROOT,'stage6C3_heatmap_mid20to80.mat'));
fprintf('Saved centroid : %s\n', fullfile(ROOT,'stage6C3_centroid.csv'));

