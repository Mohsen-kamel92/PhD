function S = set_default(S, fieldName, value)
% Fills a config field only when the caller has not already supplied it.
    if ~isfield(S, fieldName) || isempty(S.(fieldName))
        S.(fieldName) = value;
    end
end

function validate_root(ROOT)
% Confirms the chosen folder looks like the expected layout, so that a wrong
% selection fails immediately with a useful message rather than partway through
% a batch.
    assert(isfolder(ROOT), 'Data root not found at %s', ROOT);

    D = dir(ROOT);
    D = D([D.isdir] & ~startsWith({D.name},'.'));

    hasParticipant = false;
    for i = 1:numel(D)
        pPath = fullfile(ROOT, D(i).name);
        C = dir(pPath);
        C = C([C.isdir]);
        if any(~cellfun(@isempty, regexp({C.name},'^(CON|ECC)_\d+$','once')))
            hasParticipant = true;
            break;
        end
    end

       % A folder holding only the processed group file is a valid root for the
    % Stage 6 analyses, which read nothing else.
    hasGroupFile = isfile(fullfile(ROOT,'groupData_stage6A.mat'));

    assert(hasParticipant || hasGroupFile, ...
        ['The selected folder does not look like the expected data root.\n' ...
         'Expected either the raw layout\n' ...
         '  <ROOT>/<participant>/<CON_75|CON_90|ECC_75|ECC_90>/<Set_N>/\n' ...
         'or a folder containing groupData_stage6A.mat\n' ...
         'Selected: %s'], ROOT);
end

function Z = interp_map(x, y, v, Xq, Yq, interpMethod, extrapMethod)
% Interpolates the channel values onto the display grid. This is for display
% only; every statistic is computed on the channel values themselves.
    x = x(:); y = y(:); v = v(:);
    ok = isfinite(x) & isfinite(y) & isfinite(v);
    F = scatteredInterpolant(x(ok), y(ok), v(ok), interpMethod, extrapMethod);
    Z = F(Xq, Yq);
end

function C = perceptual_map(n)
% Perceptually uniform sequential map. Uses turbo where available, which is
% ordered and colourful without the false boundaries jet introduces, and falls
% back to parula on older releases.
    try
        C = turbo(n);
    catch
        C = parula(n);
    end
end

function plot_map_bare(ax, xq, yq, Z, x_ch, y_ch, xc, yc, climVals, CFG, cmap)
% One interpolated map with no axis decoration and no bounding box.
%
% The electrode circles are drawn in data units rather than as scatter markers.
% Scatter markers are drawn whole regardless of the axes limits, so the ones on
% the boundary would overhang the map; a plotted circle is clipped at the edge,
% which is the intended look.

    imagesc(ax, xq, yq, Z);
    set(ax,'YDir','normal');
       hold(ax,'on');
    % Both aspect modes stay automatic, so the axes fills the rectangle it was
    % given. The true map proportions come from the panel height computed in
    % section (10) instead.
    set(ax,'DataAspectRatioMode','auto','PlotBoxAspectRatioMode','auto');

    colormap(ax, cmap);
    clim(ax, climVals);

    th  = linspace(0, 2*pi, 61);
    rad = CFG.electrodeRadius_mm;

    for e = 1:numel(x_ch)
        plot(ax, x_ch(e) + rad*cos(th), y_ch(e) + rad*sin(th), ...
            'k-', 'LineWidth', CFG.electrodeLineWidth, 'Clipping','on');
    end

    if isfinite(xc) && isfinite(yc)
        plot(ax, xc + rad*cos(th), yc + rad*sin(th), ...
            'w-', 'LineWidth', CFG.centroidLineWidth, 'Clipping','on');
    end

    set(ax,'XTick',[],'YTick',[],'Box','off','XColor','none','YColor','none');
    xlim(ax,[xq(1) xq(end)]);
    ylim(ax,[yq(1) yq(end)]);
end

function draw_bracket(x0, x1, y, labelStr)
% Horizontal bracket with downward ticks at each end, labelled above. The ends
% sit at the centres of the two panels the bracket spans.
    tick = 0.018;
    annotation('line', [x0 x1], [y y],        'LineWidth', 1.2, 'Color','k');
    annotation('line', [x0 x0], [y-tick y],   'LineWidth', 1.2, 'Color','k');
    annotation('line', [x1 x1], [y-tick y],   'LineWidth', 1.2, 'Color','k');
    annotation('textbox', [x0 y+0.005 x1-x0 0.06], 'String', labelStr, ...
        'EdgeColor','none', 'HorizontalAlignment','center', ...
        'VerticalAlignment','bottom', 'FontWeight','bold', 'FontSize', 12);
end

function draw_compass(cx, cy, r, figAspect)
% Anatomical directions: distal up, proximal down, lateral left, medial right.
% The horizontal arm is scaled by the figure aspect so the cross reads square.
    rx = r / figAspect;
    a = {'HeadStyle','vback2','HeadLength',6,'HeadWidth',6, ...
         'LineWidth',1.2,'Color','k'};
    annotation('arrow', [cx cx],    [cy cy+r], a{:});
    annotation('arrow', [cx cx],    [cy cy-r], a{:});
    annotation('arrow', [cx cx-rx], [cy cy],   a{:});
    annotation('arrow', [cx cx+rx], [cy cy],   a{:});

    t = {'EdgeColor','none','FontWeight','bold','FontSize',11, ...
         'HorizontalAlignment','center','VerticalAlignment','middle'};
    annotation('textbox', [cx-0.02      cy+r+0.005  0.04 0.04], 'String','D', t{:});
    annotation('textbox', [cx-0.02      cy-r-0.045  0.04 0.04], 'String','P', t{:});
    annotation('textbox', [cx-rx-0.045  cy-0.02     0.04 0.04], 'String','L', t{:});
    annotation('textbox', [cx+rx+0.005  cy-0.02     0.04 0.04], 'String','M', t{:});
end


